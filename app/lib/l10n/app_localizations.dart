  static String translate(
    AppLanguageOption language,
    String key,
    String fallback,
  ) {
    switch (language) {
      case AppLanguageOption.english:
        return fallback;
      case AppLanguageOption.amharic:
        return _amharic[key] ?? _amharicByEnglish[fallback] ?? fallback;
    }
  }

  static String translateText(
    AppLanguageOption language,
    String fallback,
  ) {
    switch (language) {
      case AppLanguageOption.english:
        return fallback;
      case AppLanguageOption.amharic:
        return _amharicByEnglish[fallback] ?? fallback;
    }
  }
}

extension AppLocalizationsContext on BuildContext {
  String l10n(String key, String fallback) {
    final language = watch<ThemeProvider>().appLanguage;
    return AppLocalizations.translate(language, key, fallback);
  }

  String l10nRead(String key, String fallback) {
    final language = read<ThemeProvider>().appLanguage;
    return AppLocalizations.translate(language, key, fallback);
  }

  String l10nText(String fallback) {
    final language = watch<ThemeProvider>().appLanguage;
    return AppLocalizations.translateText(language, fallback);
  }

  String l10nTextRead(String fallback) {
    final language = read<ThemeProvider>().appLanguage;
    return AppLocalizations.translateText(language, fallback);
  }
}
